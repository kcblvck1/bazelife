create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (char_length(username) between 3 and 18),
  display_name text not null check (char_length(display_name) between 1 and 28),
  gender text not null check (gender in ('male','female')),
  location text not null default 'Campus',
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  sender_username text not null,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Drop/recreate named policies so rerunning this script does not fail.
drop policy if exists "Profiles are visible to signed-in students" on public.profiles;
drop policy if exists "Students can create their own profile" on public.profiles;
drop policy if exists "Students can update their own profile" on public.profiles;
drop policy if exists "Signed-in students can read campus chat" on public.messages;
drop policy if exists "Students can send as themselves" on public.messages;

create policy "Profiles are visible to signed-in students"
  on public.profiles for select to authenticated using (true);
create policy "Students can create their own profile"
  on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Students can update their own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = id) with check (auth.uid() = id);
create policy "Signed-in students can read campus chat"
  on public.messages for select to authenticated using (true);
create policy "Students can send as themselves"
  on public.messages for insert to authenticated
  with check (
    auth.uid() = sender_id
    and sender_username = (select p.username from public.profiles p where p.id = auth.uid())
    and char_length(body) between 1 and 500
  );

-- Create a valid, unique username even if email metadata is absent or collides.
create or replace function public.handle_new_student_profile()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  requested_username text;
  safe_username text;
  suffix text;
  student_name text;
  student_gender text;
begin
  requested_username := coalesce(new.raw_user_meta_data->>'username', split_part(coalesce(new.email, ''), '@', 1), 'student');
  safe_username := regexp_replace(requested_username, '[^A-Za-z0-9_]', '', 'g');
  safe_username := left(safe_username, 18);
  if char_length(safe_username) < 3 then
    safe_username := 'student_' || left(replace(new.id::text, '-', ''), 6);
  end if;

  if exists (select 1 from public.profiles p where lower(p.username) = lower(safe_username)) then
    suffix := left(replace(new.id::text, '-', ''), 6);
    safe_username := left(safe_username, 11) || '_' || suffix;
  end if;

  student_name := left(coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), 'Student'), 28);
  student_gender := case when new.raw_user_meta_data->>'gender' = 'female' then 'female' else 'male' end;

  insert into public.profiles (id, username, display_name, gender, location)
  values (
    new.id,
    safe_username,
    student_name,
    student_gender,
    case when student_gender = 'female' then 'Female Hostel' else 'Male Hostel' end
  ) on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_student_created on auth.users;
create trigger on_auth_student_created
after insert on auth.users
for each row execute function public.handle_new_student_profile();


-- Private one-to-one messages between registered students.
create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now(),
  constraint direct_messages_distinct_users check (sender_id <> recipient_id)
);

alter table public.direct_messages enable row level security;
grant select, insert on public.direct_messages to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "Students can read their own direct messages" on public.direct_messages;
drop policy if exists "Students can send direct messages as themselves" on public.direct_messages;

create policy "Students can read their own direct messages"
  on public.direct_messages for select to authenticated
  using (auth.uid() = sender_id or auth.uid() = recipient_id);

create policy "Students can send direct messages as themselves"
  on public.direct_messages for insert to authenticated
  with check (
    auth.uid() = sender_id
    and sender_id <> recipient_id
    and char_length(body) between 1 and 500
  );

